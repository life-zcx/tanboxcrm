const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const dotenv=require('../backend/node_modules/dotenv');
dotenv.config({path:path.join(__dirname,'../backend/.env'),override:true});
const jwt=require('../backend/node_modules/jsonwebtoken');
const {prisma}=require('../backend/dist/config/db');
const {env}=require('../backend/dist/config/env');
const {chromium}=require('../frontend/node_modules/playwright-core');
async function main(){
  const output={};
  const base=env.APP_ORIGIN;
  assert.equal((await fetch(base+'/api/health')).status,200);
  assert.equal((await fetch(base+'/api/clients')).status,401);
  assert.equal((await fetch(base+'/uploads/screenshot-1-1.jpg',{method:'HEAD'})).status,401);
  const user=await prisma.adminUser.findFirst({where:{telegramChatId:{in:[...env.TELEGRAM_ALLOWED_USER_IDS]},role:'ADMIN'}});
  if(!user)throw new Error('Approved owner record missing; complete Telegram login first');
  const session=await prisma.authSession.create({data:{userId:user.id,expiresAt:new Date(Date.now()+60000)}});
  const token=jwt.sign({sub:user.id,jti:session.id},env.JWT_SECRET,{algorithm:'HS256',expiresIn:'1m',issuer:'tanbox-crm',audience:'tanbox-web'});
  let browser;
  try{
    const defaultPath=path.join(process.env.LOCALAPPDATA||'','ms-playwright/chromium-1208/chrome-win64/chrome.exe');
    browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||(fs.existsSync(defaultPath)?defaultPath:undefined)});
    const context=await browser.newContext();
    await context.addCookies([{name:'tanbox_session',value:token,url:base,httpOnly:true,sameSite:'Strict',secure:env.COOKIE_SECURE}]);
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',e=>{if(e.type()==='error')errors.push(e.text());});
    const started=Date.now();
    await page.goto(base,{waitUntil:'networkidle',timeout:15000});
    await page.getByRole('heading',{name:'Воронка сделок и заказов'}).waitFor();
    output.authenticatedPageMs=Date.now()-started;
    assert.equal(new URL(page.url()).pathname,'/deals');
    await page.getByRole('link',{name:'Клиенты',exact:true}).click();
    await page.getByRole('heading',{name:'Реестр клиентов и лидов'}).waitFor();
    await page.waitForLoadState('networkidle');
    assert.equal(new URL(page.url()).pathname,'/clients');
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('button',{name:'Переговоры',exact:true}).first().click();
    await page.getByRole('heading',{name:'Карточка клиента',exact:true}).waitFor();
    assert(/^\/clients\/[0-9a-f-]+$/.test(new URL(page.url()).pathname));
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('heading',{name:'Карточка клиента',exact:true}).waitFor();
    await page.goBack({waitUntil:'networkidle'});assert.equal(new URL(page.url()).pathname,'/clients');
    await page.goForward({waitUntil:'networkidle'});assert(/^\/clients\//.test(new URL(page.url()).pathname));
    await page.getByRole('link',{name:'Регламенты и тарифы',exact:true}).click();
    await page.getByRole('heading',{name:'База знаний TANBOX',exact:true}).waitFor();
    await page.waitForLoadState('networkidle');
    assert.equal(new URL(page.url()).pathname,'/knowledge');
    await page.getByRole('link',{name:/Загрузка переписок/}).click();
    await page.getByRole('heading',{name:'Загрузка переписки WhatsApp',exact:true}).waitFor();
    await page.waitForLoadState('networkidle');
    assert.deepEqual(errors,[]);
    output.browserErrors=errors;
    output.screensVerified=['deals','clients','client-detail','knowledge','ingest'];
    output.directUrlsReloadAndHistory=true;
    const providerResponse=await context.request.get(base+'/api/ai/status');
    assert.equal(providerResponse.status(),200);
    const provider=await providerResponse.json();
    output.telegram=provider.telegramBot;
    output.gemini=provider.providers.gemini;
    const logout=await context.request.post(base+'/api/auth/logout',{headers:{Origin:base},data:{}});
    assert.equal(logout.status(),200);
    assert.equal((await context.request.get(base+'/api/clients')).status(),401);
    output.logoutRevoked=true;
    await context.close();
  }finally{
    if(browser)await browser.close();
    await prisma.authSession.deleteMany({where:{id:session.id}});
    await prisma.$disconnect();
  }
  fs.mkdirSync(path.join(__dirname,'../test-results'),{recursive:true});
  fs.writeFileSync(path.join(__dirname,'../test-results/live-smoke.json'),JSON.stringify(output,null,2));
  console.log(JSON.stringify(output,null,2));
}
main().catch(error=>{console.error(error.message);process.exitCode=1;prisma.$disconnect();});
